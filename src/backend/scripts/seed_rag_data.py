def import_to_chromadb(clear_first: bool = False):
    """将种子数据导入 ChromaDB"""
    from memory.chroma_service import get_chroma_service

    chroma = get_chroma_service()
    import asyncio
    asyncio.run(chroma.connect())

    if clear_first:
        try:
            chroma.collection.delete(ids=chroma.collection.get(limit=10000).get("ids", []))
            logger.info("已清空 moderation_cases collection")
            if chroma._core_collection:
                chroma._core_collection.delete(
                    ids=chroma._core_collection.get(limit=10000).get("ids", [])
                )
            logger.info("已清空 core_memory collection")
        except Exception as e:
            logger.warning(f"清空 collection 失败: {e}")

    # 批量写入 moderation_cases (每次100条)
    batch_size = 100
    total = len(SEED_CASES)
    text_count = 0
    img_count = 0
    for i in range(0, total, batch_size):
        batch = SEED_CASES[i:i + batch_size]
        metadatas = []
        for c in batch:
            meta = {
                "violation_type": c["violation_type"],
                "decision": c["decision"],
                "tags": ",".join(c.get("tags", [])),
                "risk_score": c.get("risk_score", 0.5),
                "timestamp": time.time(),
                "source": "seed_data",
                # R3·G2/G3: 模拟种子标记来源与 no_decay，供检索来源加权
                "source_dataset": "simulated",
                "ground_truth": "model_labeled",
                "no_decay": True,
            }
            if c.get("modality") == "image":
                meta["modality"] = "image"
                meta["ocr_text"] = c.get("ocr_text", "")[:500]
                meta["scene_description"] = c.get("scene_description", "")[:500]
                img_count += 1
            else:
                text_count += 1
            metadatas.append(meta)
        chroma.collection.add(
            ids=[c["id"] for c in batch],
            documents=[c["content"] for c in batch],
            metadatas=metadatas,
        )
        logger.info(f"已写入 {min(i + batch_size, total)}/{total} 条到 moderation_cases")
    logger.info(f"类型分布: 文本={text_count}, 图片={img_count}")

    # 高重要性案例写入 core_memory (取top50)
    high_importance = sorted(
        [c for c in SEED_CASES if c["violation_type"] != "none"],
        key=lambda x: x["risk_score"],
        reverse=True,
    )[:50]

    if chroma._core_collection:
        chroma._core_collection.add(
            ids=[c["id"] + "_core" for c in high_importance],
            documents=[c["content"] for c in high_importance],
            metadatas=[{
                "violation_type": c["violation_type"],
                "decision": c["decision"],
                "importance": c["risk_score"],
                "timestamp": time.time(),
                "source": "seed_data",
            } for c in high_importance],
        )
        logger.info(f"已写入 {len(high_importance)} 条高重要性案例到 core_memory")

    logger.info(f"✅ 导入完成: moderation_cases={total}条, core_memory={len(high_importance)}条")


