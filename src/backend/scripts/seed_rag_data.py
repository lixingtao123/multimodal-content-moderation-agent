def stats():
    """查看当前数据统计"""
    try:
        import chromadb
        c = chromadb.PersistentClient(path="/workspace/data/chroma")
        print(f"\n{'='*50}")
        print(f"  ChromaDB 数据统计")
        print(f"{'='*50}")
        for coll_name in c.list_collections():
            coll = c.get_collection(coll_name)
            count = coll.count()
            print(f"  {coll_name}: {count} 条")
            if count > 0:
                data = coll.get(limit=min(count, 2000), include=["metadatas"])
                type_counts = {}
                for meta in data["metadatas"]:
                    vt = meta.get("violation_type", "unknown")
                    type_counts[vt] = type_counts.get(vt, 0) + 1
                for vt, cnt in sorted(type_counts.items(), key=lambda x: -x[1]):
                    bar = "█" * max(1, cnt // 5)
                    print(f"    {vt:20s}: {cnt:4d} {bar}")
        print()
    except Exception as e:
        print(f"Error: {e}")


